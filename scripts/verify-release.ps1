# ---------------------------------------------------------------------------
# Prerequisites and host classification
# ---------------------------------------------------------------------------
foreach ($tool in @('docker', 'git', 'node', $curl)) {
  if (-not (Get-Command $tool -ErrorAction SilentlyContinue)) { Exit-Prerequisite "$tool is not on PATH" }
}
& docker compose version *> $null
if ($LASTEXITCODE -ne 0) { Exit-Prerequisite 'docker compose v2 is required' }
if (-not (Test-Path $EnvFile)) {
  Exit-Prerequisite "env file not found: $EnvFile (./scripts/init-local-env.ps1 -Profile release-test -PublicOrigin https://<release-test-host>)"
}
$EnvFile = (Resolve-Path $EnvFile).Path
if ($CaCert) { $CaCert = (Resolve-Path $CaCert).Path }
elseif ($env:NODE_EXTRA_CA_CERTS -and (Test-Path $env:NODE_EXTRA_CA_CERTS)) { $CaCert = (Resolve-Path $env:NODE_EXTRA_CA_CERTS).Path }

$envValues = Read-EnvFile $EnvFile
if (-not $PublicOrigin) { $PublicOrigin = $envValues['CORS_ORIGIN'] }
$PublicOrigin = "$PublicOrigin".TrimEnd('/')
if ($PublicOrigin -notmatch '^https://[^/]+$') { Exit-Prerequisite "the public origin must be an https origin without a path (got '$PublicOrigin')" }
$script:origin = $PublicOrigin
$originUri = [Uri]$PublicOrigin
$script:resolve = if ($ProxyAddress) { '{0}:{1}:{2}' -f $originUri.Host, $originUri.Port, $ProxyAddress } else { $null }
$apiPort = if ($envValues['API_HOST_PORT']) { $envValues['API_HOST_PORT'] } else { '3000' }
$webPort = if ($envValues['WEB_HOST_PORT']) { $envValues['WEB_HOST_PORT'] } else { '8080' }
$trustProxy = ''  # read from the resolved compose configuration (step 2)
$loopbackApi = "http://127.0.0.1:$apiPort/api"

$dockerOs = (& docker info --format '{{.OperatingSystem}}' 2>$null | Out-String).Trim()
$dockerCpus = (& docker info --format '{{.NCPU}}' 2>$null | Out-String).Trim()
$dockerMem = (& docker info --format '{{.MemTotal}}' 2>$null | Out-String).Trim()
$isLinuxHost = ($PSVersionTable.PSEdition -eq 'Core') -and [bool](Get-Variable IsLinux -ValueOnly -ErrorAction SilentlyContinue)
$memGb = if ($dockerMem -match '^\d+$') { [math]::Round([double]$dockerMem / 1GB, 1) } else { 0 }
$dirty = (& git -C $repoRoot status --porcelain 2>$null | Measure-Object).Count
$reasons = @()
if (-not $ReferenceHost) { $reasons += '-ReferenceHost was not given' }
if (-not $isLinuxHost) { $reasons += 'the host is not Linux' }
if ($dockerOs -match 'Docker Desktop') { $reasons += "Docker Desktop ($dockerOs), not Docker Engine" }
if (-not $HostDescription) { $reasons += 'no -HostDescription' }
# The gate is a clean checkout built by this run on a host of at least 2 vCPU and 4 GB.
if ($dirty -gt 0) { $reasons += "$dirty uncommitted path(s): not a clean checkout" }
if ($SkipBuild) { $reasons += '-SkipBuild reuses images this run did not build' }
if (-not ($dockerCpus -match '^\d+$' -and [int]$dockerCpus -ge 2)) { $reasons += "fewer than 2 vCPU ($dockerCpus)" }
if ($memGb -lt 3.5) { $reasons += "less than 4 GB of memory ($memGb GB visible to Docker)" }
$authoritative = ($reasons.Count -eq 0)
$evidence['mode'] = $(if ($authoritative) { 'AUTHORITATIVE (reference release host)' } else { 'INFORMATIVE (' + ($reasons -join '; ') + ')' })
$evidence['host'] = ('{0}; docker: {1}, {2} CPU, {3} GB{4}' -f [Environment]::OSVersion.VersionString, $dockerOs, $dockerCpus, $memGb, $(if ($HostDescription) { "; $HostDescription" } else { '' }))
$evidence['publicOrigin'] = $PublicOrigin
$evidence['loopbackPorts'] = "api 127.0.0.1:$apiPort, web 127.0.0.1:$webPort"
$evidence['commit'] = (& git -C $repoRoot rev-parse --short HEAD 2>$null | Out-String).Trim()
$evidence['workingTree'] = $(if ($dirty -eq 0) { 'clean' } else { "$dirty uncommitted path(s): not a clean checkout" })
Write-Host "Mode: $($evidence['mode'])"
Write-Host "Host: $($evidence['host'])"
Write-Host "Origin: $PublicOrigin; compose project: $ProjectName; commit $($evidence['commit']) ($($evidence['workingTree']))"

# Never touch a deployment: the check runs only as its own, not yet running project.
if ($ProjectName -eq 'cashlens-prod') { Exit-Prerequisite "-ProjectName cashlens-prod is the deployment project name; use a dedicated check project" }
$existing = @(& docker compose -p $ProjectName --env-file $EnvFile -f $composeFile ps -a -q 2>$null | Where-Object { $_ })
if ($existing.Count -gt 0) {
  Exit-Prerequisite "compose project '$ProjectName' already has $($existing.Count) container(s); stop it first (docker compose -p $ProjectName ... down, volumes are kept)"
}

# The env file must stay out of git (CFG-006). A file outside the repository cannot be committed.
$envInRepo = $EnvFile.StartsWith($repoRoot, [StringComparison]::OrdinalIgnoreCase)
& git -C $repoRoot check-ignore -q $EnvFile 2>$null
$ignored = (-not $envInRepo) -or ($LASTEXITCODE -eq 0)
$tracked = $false
if ($envInRepo) {
  & git -C $repoRoot ls-files --error-unmatch $EnvFile *> $null
  $tracked = ($LASTEXITCODE -eq 0)
}
Add-Result 'env file ignored and untracked' ($ignored -and -not $tracked) ("in repository=$envInRepo ignored=$ignored tracked=$tracked")
Add-Result 'env file is production' ($envValues['NODE_ENV'] -eq 'production' -and $envValues['CORS_ORIGIN'] -like 'https://*') ("NODE_ENV=$($envValues['NODE_ENV']), CORS_ORIGIN=$($envValues['CORS_ORIGIN']), EMAIL_TRANSPORT=$($envValues['EMAIL_TRANSPORT'])")

$userEmail = "release-check-$runId@example.test"
$legacyEmail = "release-legacy-admin-$runId@example.test"
$password = 'Rc-' + [guid]::NewGuid().ToString('N') + '!9'
$apiContainerStopped = $false

try {
  # -------------------------------------------------------------------------
  # 1. Secret scan and migration matrix (reused scripts)
  # -------------------------------------------------------------------------
  $scanArgs = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', (Join-Path $repoRoot 'scripts/scan-secrets.ps1'))
  if ($SecretScanBaseRef) { $scanArgs += @('-BaseRef', $SecretScanBaseRef) }
  $scanOut = & $psExe @scanArgs 2>&1 | ForEach-Object { "$_" }
  $scanExit = $LASTEXITCODE
  $evidence['secretScan'] = (($scanOut | Where-Object { $_ -match 'gitleaks|Working tree|History|exceptions' }) -join ' | ')
  Add-Result 'secret scan (scan-secrets.ps1)' ($scanExit -eq 0) ("exit $scanExit")
  if ($scanExit -ne 0) { $scanOut | Select-Object -Last 20 | ForEach-Object { Write-Host "  $_" } }

  $adminUrl = $MigrationAdminUrl
  if (-not $adminUrl) {
    $listener = New-Object Net.Sockets.TcpListener ([Net.IPAddress]::Loopback, 0)
    $listener.Start(); $pgPort = $listener.LocalEndpoint.Port; $listener.Stop()
    $pgName = "$ProjectName-migrations-$runId"
    $pgPassword = [guid]::NewGuid().ToString('N')
    # Disposable server for the migration matrix: no named volume, removed on exit.
    & docker run -d --rm --name $pgName -e POSTGRES_USER=migration_check -e "POSTGRES_PASSWORD=$pgPassword" -e POSTGRES_DB=postgres -p "127.0.0.1:${pgPort}:5432" postgres:16-alpine *> $null
    if ($LASTEXITCODE -ne 0) { Exit-Prerequisite 'could not start the disposable PostgreSQL container for the migration matrix' }
    $cleanup.Add({ & docker rm -f $pgName *> $null }.GetNewClosure())
    $ready = Wait-Until { & docker exec $pgName pg_isready -U migration_check -d postgres *> $null; $LASTEXITCODE -eq 0 } 60
    Start-Sleep -Seconds 2
    if (-not $ready) { Exit-Prerequisite 'the disposable PostgreSQL container did not become ready' }
    $adminUrl = "postgresql://migration_check:$pgPassword@127.0.0.1:$pgPort/postgres"
  }
  # Passed through the environment, never on a command line that `ps` shows.
  $previousAdminUrl = $env:MIGRATION_CHECK_ADMIN_URL
  $env:MIGRATION_CHECK_ADMIN_URL = $adminUrl
  $migrationOut = & $psExe -NoProfile -ExecutionPolicy Bypass -File (Join-Path $repoRoot 'apps/api/test/scripts/verify-migrations.ps1') 2>&1 | ForEach-Object { "$_" }
  $migrationExit = $LASTEXITCODE
  $env:MIGRATION_CHECK_ADMIN_URL = $previousAdminUrl
  # Greedy up to the last '@' of the URL, so a password containing '@' is fully hidden.
  $hideUrlPassword = { param($text) $text -replace '://([^:/@\s]+):\S*@', '://$1:***@' }
  $evidence['migrations'] = & $hideUrlPassword ((($migrationOut | Where-Object { $_ -match '\b(PASS|FAIL)\b' } | ForEach-Object { ($_ -replace '\s{2,}', ' ').Trim() }) -join ' | '))
  Add-Result 'migration matrix (verify-migrations.ps1)' ($migrationExit -eq 0) ("exit $migrationExit")
  if ($migrationExit -ne 0) { $migrationOut | Select-Object -Last 20 | ForEach-Object { Write-Host "  $(& $hideUrlPassword $_)" } }

  # -------------------------------------------------------------------------
  # 2. Compose configuration (parsed in memory; it contains resolved secrets)
  # -------------------------------------------------------------------------
  $configJson = (& docker compose -p $ProjectName --env-file $EnvFile -f $composeFile config --format json 2>$null | Out-String)
  $config = ConvertFrom-JsonSafe $configJson
  $configJson = $null
  if ($null -eq $config) {
    Add-Result 'compose config' $false 'docker compose config failed (a required variable is missing from the env file?)'
    throw 'compose config failed'
  }
  $services = Get-Prop $config 'services'
  $bindings = @()
  $loopbackOnly = $true
  foreach ($name in @('api', 'web')) {
    $ports = @(Get-Prop (Get-Prop $services $name) 'ports')
    if ($ports.Count -eq 0) { $loopbackOnly = $false }
    foreach ($p in $ports) {
      $bindings += '{0}={1}:{2}' -f $name, (Get-Prop $p 'host_ip'), (Get-Prop $p 'published')
      if ((Get-Prop $p 'host_ip') -ne '127.0.0.1') { $loopbackOnly = $false }
    }
  }
  $pgPorts = @(Get-Prop (Get-Prop $services 'postgres') 'ports') | Where-Object { $_ }
  $subnet = @(Get-Prop (Get-Prop (Get-Prop (Get-Prop $config 'networks') 'cashlens_net') 'ipam') 'config') | ForEach-Object { Get-Prop $_ 'subnet' }
  $pinned = ($subnet -contains '172.28.0.0/24')
  $servicesOnNet = @('postgres', 'migrate', 'api', 'web') | Where-Object {
    $networks = Get-Prop (Get-Prop $services $_) 'networks'
    ($null -ne $networks) -and (($networks -is [array] -and $networks -contains 'cashlens_net') -or $null -ne $networks.PSObject.Properties['cashlens_net'])
  }
  Add-Result 'config: API and web on 127.0.0.1 only' $loopbackOnly ($bindings -join ', ')
  Add-Result 'config: PostgreSQL unpublished' (@($pgPorts).Count -eq 0) ("published ports: $(@($pgPorts).Count)")
  Add-Result 'config: pinned cashlens_net' ($pinned -and @($servicesOnNet).Count -eq 4) ("subnet $($subnet -join ','); services on it: $($servicesOnNet -join ',')")
  # What the API container will actually run with (shell variables override the
  # env file, and the compose file has defaults): only these three keys are read.
  $apiEnvironment = Get-Prop (Get-Prop $services 'api') 'environment'
  $trustProxy = [string](Get-Prop $apiEnvironment 'TRUST_PROXY')
  $effectiveNodeEnv = [string](Get-Prop $apiEnvironment 'NODE_ENV')
  $effectiveCors = [string](Get-Prop $apiEnvironment 'CORS_ORIGIN')
  Add-Result 'config: API runs in production with the public https origin' ($effectiveNodeEnv -eq 'production' -and $effectiveCors -eq $PublicOrigin) ("NODE_ENV=$effectiveNodeEnv, CORS_ORIGIN=$effectiveCors, TRUST_PROXY=$trustProxy")
  $apiEnvironment = $null; $config = $null; $services = $null

  # -------------------------------------------------------------------------
  # 3. Build and migrate before the API starts
  # -------------------------------------------------------------------------
  if (-not $SkipBuild) {
    $buildOut = Invoke-Compose build
    Add-Result 'build release images' ($LASTEXITCODE -eq 0) ("exit $LASTEXITCODE")
    if ($LASTEXITCODE -ne 0) { $buildOut | Select-Object -Last 30 | ForEach-Object { Write-Host "  $_" }; throw 'build failed' }
  }
  $migrateOut = Invoke-Compose run --rm migrate
  $migrateExit = $LASTEXITCODE
  $evidence['migrate'] = (($migrateOut | Where-Object { $_ -match 'applied|No pending' }) | Select-Object -Last 1) -join ' | '
  Add-Result 'run --rm migrate (before api)' ($migrateExit -eq 0) ("exit $migrateExit")
  if ($migrateExit -ne 0) { $migrateOut | Select-Object -Last 20 | ForEach-Object { Write-Host "  $_" }; throw 'migrate failed' }

  # -------------------------------------------------------------------------
  # 4. An http:// CORS_ORIGIN makes startup fail
  # -------------------------------------------------------------------------
  $probe = "$ProjectName-cors-probe-$runId"
  $cleanup.Add({ & docker rm -f $probe *> $null }.GetNewClosure())
  $null = Invoke-Compose run -d --no-deps --name $probe -e CORS_ORIGIN=http://insecure-origin.example.test api
  $stopped = Wait-Until { ((& docker inspect -f '{{.State.Running}}' $probe 2>$null | Out-String).Trim()) -eq 'false' } 60
  $probeExit = (& docker inspect -f '{{.State.ExitCode}}' $probe 2>$null | Out-String).Trim()
  $probeLog = (& docker logs $probe 2>&1 | Out-String)
  & docker rm -f $probe *> $null
  $rejected = $stopped -and $probeExit -ne '0' -and $probeLog -match 'app\.start_failed' -and $probeLog -match 'CORS_ORIGIN'
  Add-Result 'http:// CORS_ORIGIN rejected at startup' $rejected ("stopped=$stopped exit=$probeExit")

  # -------------------------------------------------------------------------
  # 5. Start the stack; loopback health
  # -------------------------------------------------------------------------
  $upOut = Invoke-Compose up -d
  if ($LASTEXITCODE -ne 0) { $upOut | Select-Object -Last 20 | ForEach-Object { Write-Host "  $_" } }
  $healthy = Wait-Until { (Invoke-Http "$loopbackApi/health/ready").Status -eq 200 } 180 3
  Add-Result 'loopback http /api/health/ready = 200' $healthy
  if (-not $healthy) { throw 'the API did not become ready' }
  $null = Wait-Until { (Invoke-Http "$PublicOrigin/").Status -eq 200 } 60 3

  # The kept volume may still hold synthetic administrators of an earlier,
  # aborted run; they would make the bootstrap refuse (one administrator only).
  $bootstrap = 'dist/src/scripts/bootstrap-admin.js'
  $synthetic = '(release-check|release-legacy-admin)-\d+@example\.test'
  $leftovers = @(Invoke-Compose exec -T api node $bootstrap --list-admins | ForEach-Object { [regex]::Match($_, $synthetic).Value } | Where-Object { $_ } | Select-Object -Unique)
  foreach ($email in $leftovers) { $null = Invoke-Compose exec -T api node $bootstrap --revoke --email $email }
  $otherAdmins = @(Invoke-Compose exec -T api node $bootstrap --list-admins | Where-Object { $_ -match '@' })
  $evidence['adminsBeforeCheck'] = "synthetic leftovers revoked: $($leftovers.Count); other administrators: $($otherAdmins.Count)"
  Add-Result 'no administrator before the bootstrap check' ($otherAdmins.Count -eq 0) ("leftover synthetic admins revoked: $($leftovers.Count); remaining: $($otherAdmins.Count)$(if ($otherAdmins.Count) { ' (the release-test database already has an administrator; use a fresh check project)' })")

  # -------------------------------------------------------------------------
  # 6. Through the proxy: web app, bundle, readiness
  # -------------------------------------------------------------------------
  $index = Invoke-Http "$PublicOrigin/"
  Add-Result 'https / serves the web app' ($index.Status -eq 200 -and $index.Body -match 'id="root"') ("status $($index.Status)$(if ($index.Error) { ': ' + $index.Error })")
  $scripts = @([regex]::Matches($index.Body, 'src="(/assets/[^"]+\.js)"') | ForEach-Object { $_.Groups[1].Value })
  $checked = New-Object System.Collections.Generic.HashSet[string]
  $queue = New-Object System.Collections.Generic.Queue[string]
  foreach ($s in $scripts) { $queue.Enqueue($s) }
  $relativeApi = $false; $absolute = @()
  while ($queue.Count -gt 0 -and $checked.Count -lt 60) {
    $path = $queue.Dequeue()
    if (-not $checked.Add($path)) { continue }
    $chunk = (Invoke-Http "$PublicOrigin$path").Body
    if ($chunk -match '["''`]/api["''`/]') { $relativeApi = $true }
    $absolute += @([regex]::Matches($chunk, 'https?://[A-Za-z0-9.\-]+(?::\d+)?/api\b') | ForEach-Object { $_.Value })
    if ($chunk -match 'localhost:(3000|13000)|127\.0\.0\.1:3000') { $absolute += $Matches[0] }
    foreach ($m in [regex]::Matches($chunk, '(?:/assets/|\./)([A-Za-z0-9_\-.]+\.js)')) { $queue.Enqueue('/assets/' + $m.Groups[1].Value) }
  }
  $absolute = @($absolute | Select-Object -Unique)
  $unchecked = $queue.Count  # never pass on a partially scanned bundle
  Add-Result 'bundle uses relative /api, no absolute API origin' ($scripts.Count -gt 0 -and $relativeApi -and $absolute.Count -eq 0 -and $unchecked -eq 0) ("chunks $($checked.Count), unchecked $unchecked; relative /api=$relativeApi; absolute: $(if ($absolute.Count) { $absolute -join ', ' } else { 'none' })")
  $hsts = [bool]($index.Headers -match '(?im)^strict-transport-security:\s*max-age=\d+')
  $plainUri = 'http://{0}/' -f $originUri.Host
  $plainResolve = if ($ProxyAddress) { '{0}:80:{1}' -f $originUri.Host, $ProxyAddress } else { $null }
  $plain = Invoke-Http $plainUri -Resolve $plainResolve
  $location = [regex]::Match($plain.Headers, '(?im)^location:\s*(\S+)').Groups[1].Value
  Add-Result 'proxy: HSTS on https, http redirects to https' ($hsts -and $plain.Status -in 301, 308 -and $location -like "$PublicOrigin/*") ("hsts=$hsts; http status $($plain.Status) -> $location")
  $proxyReady = Invoke-Http "$PublicOrigin/api/health/ready"
  Add-Result 'https /api/health/ready = 200 through the proxy' ($proxyReady.Status -eq 200) ("status $($proxyReady.Status)")

  # -------------------------------------------------------------------------
  # 7. Login through the proxy: cookie attributes and an authenticated call
  # -------------------------------------------------------------------------
  $jar = Join-Path $workDir 'cookies.txt'
  $credentials = @{ email = $userEmail; password = $password } | ConvertTo-Json -Compress
  $register = Invoke-Http "$PublicOrigin/api/auth/register" -Method POST -Body (@{ email = $userEmail; password = $password; fullName = 'Release Check' } | ConvertTo-Json -Compress)
  Add-Result 'register through the proxy' ($register.Status -eq 201) ("status $($register.Status)")
  $login = Invoke-Http "$PublicOrigin/api/auth/login" -Method POST -Body $credentials -CookieJar $jar
  $setCookies = @($login.Headers -split "`r?`n" | Where-Object { $_ -match '^set-cookie:' })
  $badCookies = @($setCookies | Where-Object { $_ -notmatch ';\s*Secure(;|$)' -or $_ -notmatch ';\s*HttpOnly(;|$)' -or $_ -notmatch ';\s*SameSite=Lax(;|$)' })
  $cookieNames = ($setCookies | ForEach-Object { ($_ -replace '^set-cookie:\s*', '') -replace '=.*$', '' }) -join ', '
  $missingCookies = @('accessToken', 'refreshToken' | Where-Object { ($cookieNames -split ', ') -notcontains $_ })
  Add-Result 'login sets Secure; HttpOnly; SameSite=Lax cookies' ($login.Status -eq 200 -and $missingCookies.Count -eq 0 -and $badCookies.Count -eq 0) ("status $($login.Status); cookies: $cookieNames$(if ($missingCookies.Count) { '; missing: ' + ($missingCookies -join ', ') })")
  $me = Invoke-Http "$PublicOrigin/api/auth/me" -CookieJar $jar
  Add-Result 'authenticated same-origin call with the cookies' ($me.Status -eq 200) ("GET /api/auth/me status $($me.Status)")

  # -------------------------------------------------------------------------
  # 8. TRUST_PROXY covers the peer address the API observes behind the proxy
  # -------------------------------------------------------------------------
  $nonce = "trust-proxy-$runId"
  $probeResponse = Invoke-Http "$PublicOrigin/api/release-check/$nonce"
  $observed = $null; $forwardedSecure = $null
  $null = Wait-Until {
    foreach ($line in (Get-ApiLogLines | Where-Object { $_ -like "*$nonce*" })) {
      $entry = ConvertFrom-JsonSafe $line
      $address = Get-Prop (Get-Prop $entry 'req') 'remoteAddress'
      if ($address) { $script:observed = $address; return $true }
    }
    return $false
  } 20
  $covered = [bool]($observed -and (Test-TrustProxyCovers $trustProxy $observed))
  $evidence['trustProxy'] = "observed remoteAddress=$observed; TRUST_PROXY=$trustProxy; covered=$covered"
  Add-Result 'TRUST_PROXY covers the observed proxy peer' $covered ("remoteAddress=$(if ($observed) { $observed } else { 'not found in the API log' }); TRUST_PROXY=$trustProxy; probe status $($probeResponse.Status)")

  # -------------------------------------------------------------------------
  # 9. Direct loopback login without forwarded headers is refused
  # -------------------------------------------------------------------------
  $direct = Invoke-Http "$loopbackApi/auth/login" -Method POST -Body $credentials
  $directCookies = @($direct.Headers -split "`r?`n" | Where-Object { $_ -match '^set-cookie:' }).Count
  Add-Result 'direct http login = 403 HTTPS_REQUIRED' ($direct.Status -eq 403 -and (Get-ErrorCode $direct) -eq 'HTTPS_REQUIRED' -and $directCookies -eq 0) ("status $($direct.Status), code $(Get-ErrorCode $direct), cookies $directCookies")

  # -------------------------------------------------------------------------
  # 10. Admin bootstrap, idempotent rerun, and the upgrade review
  # -------------------------------------------------------------------------
  $first = Invoke-Compose exec -T api node $bootstrap --email $userEmail
  $firstExit = $LASTEXITCODE
  $again = Invoke-Compose exec -T api node $bootstrap --email $userEmail
  $againExit = $LASTEXITCODE
  Add-Result 'admin bootstrap' ($firstExit -eq 0) ("exit ${firstExit}: $(($first | Select-Object -Last 1))")
  Add-Result 'admin bootstrap rerun is idempotent' ($againExit -eq 0) ("exit ${againExit}: $(($again | Select-Object -Last 1))")

  # An administrator nobody approved, as an upgraded database may contain.
  $legacy = Invoke-Http "$PublicOrigin/api/auth/register" -Method POST -Body (@{ email = $legacyEmail; password = $password; fullName = 'Legacy Admin' } | ConvertTo-Json -Compress)
  $sql = "UPDATE ""User"" SET role = 'ADMIN' WHERE email = '$legacyEmail';"
  $null = $sql | & docker compose -p $ProjectName --env-file $EnvFile -f $composeFile exec -T postgres sh -c 'psql -v ON_ERROR_STOP=1 -U $POSTGRES_USER -d $POSTGRES_DB' 2>&1
  $before = @(Invoke-Compose exec -T api node $bootstrap --list-admins)
  $listed = [bool]($before -match [regex]::Escape($legacyEmail))
  $revoke = Invoke-Compose exec -T api node $bootstrap --revoke --email $legacyEmail
  $revokeExit = $LASTEXITCODE
  $after = @(Invoke-Compose exec -T api node $bootstrap --list-admins)
  $evidence['listAdmins'] = ($before | Where-Object { $_ -match '@' }) -join ' | '
  $revoked = ($legacy.Status -eq 201) -and $listed -and $revokeExit -eq 0 -and -not ($after -match [regex]::Escape($legacyEmail)) -and [bool]($after -match [regex]::Escape($userEmail))
  Add-Result 'upgrade review: --list-admins recorded, unapproved admin revoked' $revoked ("listed=$listed revoke exit=$revokeExit")

  # The check's own administrator is synthetic: revoke it so the kept volume
  # lets the next run bootstrap again.
  $null = Invoke-Compose exec -T api node $bootstrap --revoke --email $userEmail
  $finalAdmins = @(Invoke-Compose exec -T api node $bootstrap --list-admins | Where-Object { $_ -match '@' })
  Add-Result 'synthetic administrator revoked after the check' ($finalAdmins.Count -eq 0) ("administrators left: $($finalAdmins.Count)")

  # -------------------------------------------------------------------------
  # 11. Restart and persistence (SC-013)
  # -------------------------------------------------------------------------
  $description = "release-check-$runId"
  $created = Invoke-Http "$PublicOrigin/api/transactions" -Method POST -CookieJar $jar -Body (@{
      amount = 123456; currency = 'VND'; direction = 'EXPENSE'
      transactionTime = [DateTime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ss.fffZ'); description = $description
    } | ConvertTo-Json -Compress)
  Add-Result 'create a transaction through the proxy' ($created.Status -eq 201) ("status $($created.Status)")

  function Get-TransactionCount {
    $null = Invoke-Http "$PublicOrigin/api/auth/login" -Method POST -Body $credentials -CookieJar $jar
    $list = Invoke-Http "$PublicOrigin/api/transactions?search=$description" -CookieJar $jar
    $data = Get-Prop (ConvertFrom-JsonSafe $list.Body) 'data'
    $items = if ($data -is [array]) { $data } elseif (Get-Prop $data 'items') { Get-Prop $data 'items' } else { Get-Prop $data 'data' }
    return @(@($items) | Where-Object { $_ -and (Get-Prop $_ 'description') -eq $description }).Count
  }

  $null = Invoke-Compose restart api
  $back = Wait-Until { (Invoke-Http "$loopbackApi/health/ready").Status -eq 200 } 120 3
  $countAfterRestart = Get-TransactionCount
  Add-Result 'API restart: account and one transaction persist' ($back -and $countAfterRestart -eq 1) ("ready=$back count=$countAfterRestart")

  $null = Invoke-Compose down
  $null = Invoke-Compose up -d
  $back = Wait-Until { (Invoke-Http "$loopbackApi/health/ready").Status -eq 200 } 180 3
  $null = Wait-Until { (Invoke-Http "$PublicOrigin/api/health/ready").Status -eq 200 } 60 3
  $countAfterRecreate = Get-TransactionCount
  Add-Result 'down/up (volumes kept): no loss, no duplicates' ($back -and $countAfterRecreate -eq 1) ("ready=$back count=$countAfterRecreate")

  # -------------------------------------------------------------------------
  # 12. Dependency outage and recovery
  # -------------------------------------------------------------------------
  $null = Invoke-Compose stop postgres
  $notReady = Wait-Until { (Invoke-Http "$loopbackApi/health/ready").Status -eq 503 } 60 2
  $dataCall = Invoke-Http "$PublicOrigin/api/transactions" -CookieJar $jar
  Add-Result 'outage: readiness 503 while PostgreSQL is down' $notReady
  Add-Result 'outage: data call 503 SERVICE_UNAVAILABLE' ($dataCall.Status -eq 503 -and (Get-ErrorCode $dataCall) -eq 'SERVICE_UNAVAILABLE') ("status $($dataCall.Status), code $(Get-ErrorCode $dataCall)")
  $null = Invoke-Compose start postgres
  $recovered = Wait-Until { (Invoke-Http "$loopbackApi/health/ready").Status -eq 200 } 120 3
  $dataAgain = Invoke-Http "$PublicOrigin/api/transactions" -CookieJar $jar
  Add-Result 'outage: recovery without an API restart' ($recovered -and $dataAgain.Status -eq 200) ("ready=$recovered data status $($dataAgain.Status)")

  # -------------------------------------------------------------------------
  # 13. Graceful shutdown
  # -------------------------------------------------------------------------
  # stdout only: a compose warning on stderr must not be taken for the id.
  $apiId = (& docker compose -p $ProjectName --env-file $EnvFile -f $composeFile ps -q api 2>$null | Where-Object { $_ -match '^[0-9a-f]{12,}$' } | Select-Object -First 1)
  $started = Get-Date
  $null = Invoke-Compose stop -t 30 api
  $apiContainerStopped = $true
  $elapsed = [math]::Round(((Get-Date) - $started).TotalSeconds, 1)
  $state = (& docker inspect -f '{{.State.ExitCode}} {{.State.OOMKilled}}' $apiId 2>$null | Out-String).Trim()
  $graceful = [bool]((& docker logs --tail 50 $apiId 2>&1 | Out-String) -match 'shut down gracefully')
  $exitCode = ($state -split ' ')[0]
  Add-Result 'graceful shutdown on SIGTERM' ($graceful -and $exitCode -ne '137' -and $elapsed -lt 30) ("exit $exitCode after ${elapsed}s; graceful log=$graceful")
}
catch {
  Add-Result 'verification aborted' $false ($_.Exception.Message)
}
finally {
  foreach ($step in $cleanup) { & $step }
  if (-not $KeepRunning) { $null = Invoke-Compose down }
  elseif ($apiContainerStopped) { $null = Invoke-Compose up -d }
  Remove-Item -Recurse -Force $workDir -ErrorAction SilentlyContinue
}

