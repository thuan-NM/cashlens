Write-Host ("{0} checks, {1} failed; volumes kept ({2}_cashlens_prod_postgres_data)" -f $results.Count, $failed, $ProjectName)
if ($failed -gt 0) {
  Write-Host 'RESULT: FAIL'
  exit 1
}
if ($authoritative) {
  Write-Host 'RESULT: PASS (authoritative: reference release host)'
  exit 0
}
Write-Host 'RESULT: PASS (INFORMATIVE ONLY: not the reference release host; this is not the release gate)'
exit 3
