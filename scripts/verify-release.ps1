<#
.SYNOPSIS
Clean-checkout container release verification for CashLens (T100).

.DESCRIPTION
Builds and runs the production compose stack (docker-compose.prod.yml) with a
release-test env file, behind the operator's TLS reverse proxy, and checks
OPS-001-OPS-009, AUTH-003, SEC-009, CFG-006, and SC-013:

  1. Secret scan (scripts/scan-secrets.ps1) and migration matrix
     (apps/api/test/scripts/verify-migrations.ps1, against a disposable
     PostgreSQL container unless -MigrationAdminUrl is given).
  2. Compose configuration: API and web published on 127.0.0.1 only,
     PostgreSQL unpublished, pinned cashlens_net (172.28.0.0/24).
  3. Build, then `run --rm migrate` before the API starts.
  4. An http:// CORS_ORIGIN makes API startup fail.
  5. Through the proxy (https://<release-test-host>): the web app is served,
     its bundle calls the relative /api with no absolute API origin,
     /api/health/ready returns 200, login sets Secure; HttpOnly; SameSite=Lax
     cookies, and an authenticated same-origin call with them succeeds.
  6. TRUST_PROXY: the peer address the API logged (`req.remoteAddress`) for a
     request sent through the proxy must be covered by TRUST_PROXY. The
     observed address and TRUST_PROXY are recorded.
  7. Direct loopback login without forwarded headers returns 403
     HTTPS_REQUIRED; loopback /api/health/ready returns 200.
  8. Admin bootstrap (SEC-009), an idempotent rerun, and the upgrade review:
     `--list-admins` is recorded and an unapproved administrator on the
     existing database is revoked.
  9. Restart and persistence: after an API restart and a full `down`/`up`
     (volumes kept), the account and exactly one copy of a transaction remain.
 10. Dependency outage: with PostgreSQL stopped, readiness and data calls
     return 503; both recover when it starts again.
 11. Graceful shutdown: SIGTERM stops the API within its grace period and it
     logs the graceful shutdown.

Where it runs. The result is AUTHORITATIVE only on the reference release host
(plan.md "Reference release host and release-test profile"): Linux, Docker
Engine (not Docker Desktop), the documented proxy terminating TLS, and
-ReferenceHost with -HostDescription given. Anywhere else, including Docker
Desktop, every check still runs but the result is INFORMATIVE and is never the
release gate.

Host state. The script needs only Docker with compose v2, git, curl, node, the
env file, and a running proxy for the public origin. It never deletes a volume:
the stack's PostgreSQL volume (<project>_cashlens_prod_postgres_data) is kept
between runs, and `down` is called without -v. The disposable migration-check
PostgreSQL container has no named volume and is removed on exit. Nothing
secret is printed: env values other than origins, ports, and TRUST_PROXY are
never echoed, and all identities are synthetic (@example.test).

Exit codes: 0 all checks passed on the reference host (authoritative);
3 all checks passed on another host (informative only, not the release gate);
1 a check failed; 2 a prerequisite is missing.

.PARAMETER EnvFile
Release-test env file. Default: .env.release-test at the repository root,
generated by ./scripts/init-local-env.ps1 -Profile release-test -PublicOrigin
https://<release-test-host>. API_HOST_PORT and WEB_HOST_PORT may be added to it
when the defaults (3000, 8080) are taken on the host.

.PARAMETER PublicOrigin
The https origin the proxy serves. Default: CORS_ORIGIN from the env file.

.PARAMETER ProxyAddress
Optional IP address that the public host name resolves to (passed to curl
--resolve), for release-test host names without DNS. Nothing on the host is
changed.

.PARAMETER CaCert
PEM file of the test CA that signed the proxy certificate. Default:
$env:NODE_EXTRA_CA_CERTS; otherwise the system trust store is used.

.PARAMETER ProjectName
Compose project name. Default: cashlens-release-check. Only one stack using
docker-compose.prod.yml can run on a host at a time (pinned subnet).

.PARAMETER MigrationAdminUrl
postgresql:// maintenance URL for the migration matrix. Default: a disposable
postgres:16-alpine container on a free loopback port.

.PARAMETER SecretScanBaseRef
Passed to scan-secrets.ps1 as -BaseRef when given.

.PARAMETER ReferenceHost
Claims the run is on the reference release host. It is honoured only on Linux
with Docker Engine and with -HostDescription.

.PARAMETER HostDescription
Reference host description for release evidence (for example
"CI runner, Ubuntu 24.04, 2 vCPU, 4 GB, SSD").

.PARAMETER SkipBuild
Uses the already built release images.

.PARAMETER KeepRunning
Leaves the stack running at the end (default: `down`, volumes kept).

.EXAMPLE
./scripts/verify-release.ps1 -ReferenceHost -HostDescription "CI runner, Ubuntu 24.04, 2 vCPU, 4 GB, SSD"

.EXAMPLE
./scripts/verify-release.ps1 -ProxyAddress 127.0.0.1 -CaCert ./tmp/test-ca.pem
#>
